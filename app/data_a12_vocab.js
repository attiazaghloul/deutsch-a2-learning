(function mergeA12Vocabulary() {
  if (!Array.isArray(window.A1_BOOK)) return;
  /* Spaces and hyphens are ignored, so "weh tun" and "wehtun" are the same card. */
  const key = word => String(word || '').replace(/\([^)]*\)/g, '').replace(/^(der|die|das)\s+/i, '').split(',')[0]
    .replace(/[\s-]+/g, '').trim().toLocaleLowerCase('de-DE');
  /* the new spelling of a card → the key the older card used */
  const aliases = { schmerz: 'schmerzen', partizipii: 'partizip', berg: 'berge' };
  const fresh = window.A1_VOCAB_12;
  const photos = new Map();
  window.A1_BOOK.filter(chapter => fresh[chapter.num]).forEach(chapter => {
    (chapter.vocab || []).forEach(card => {
      const id = key(card.w);
      if (card.img && !photos.has(id)) photos.set(id, card.img);
    });
  });
  window.A1_BOOK.forEach(chapter => {
    const list = fresh[chapter.num];
    if (!list) return;
    const previous = (chapter.vocab || []).map((card, index) => ({ card, index, key: key(card.w) }));
    const byKey = new Map();
    previous.forEach(entry => { if (!byKey.has(entry.key)) byKey.set(entry.key, entry); });
    const claimed = new Set();
    const merged = list.map(card => {
      const own = key(card.w);
      const id = byKey.has(own) ? own : (aliases[own] || own);
      const old = claimed.has(id) ? null : byKey.get(id);
      if (old) claimed.add(id);
      const next = { ...card, img: (old ? old.card.img : '') || photos.get(id) || '' };
      if (old) next.legacy = { index: old.index, w: old.card.w };
      return next;
    });
    const extras = previous.filter(entry => !claimed.has(entry.key)).map(entry => ({
      ...entry.card, cat: 'Weitere nützliche Wörter', catAr: 'كلمات وعبارات إضافية مفيدة', legacy: { index: entry.index, w: entry.card.w }
    }));
    chapter.vocab = [...merged, ...extras];
    chapter.vocabSummary = {
      title: 'Wortschatz zum Kapitel',
      titleAr: 'مفردات الوحدة',
      note: 'Alle Wörter aus dem Lernwortschatz und der Wortliste von Netzwerk neu A1.2, nach Themen sortiert – mit einfacher Erklärung und Beispielsatz.',
      noteAr: 'كل كلمات الـ Lernwortschatz وقائمة الكلمات للوحدة من Netzwerk neu A1.2، مرتبة حسب الموضوع، مع شرح بسيط بالألماني ومثال وترجمة.'
    };
  });
})();
