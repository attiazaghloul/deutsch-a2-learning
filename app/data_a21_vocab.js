(function mergeA21Vocabulary() {
  if (!Array.isArray(window.BOOK0)) return;
  /* Spaces and hyphens are ignored, so "teilnehmen an" and "teilnehmen" match the same card. */
  const key = word => String(word || '').replace(/\([^)]*\)/g, '').replace(/^(der|die|das)\s+/i, '').split(',')[0].trim()
    .replace(/\s+(an|auf|über|zu|für|um)$/i, '').replace(/[\s-]+/g, '').trim().toLocaleLowerCase('de-DE');
  const fresh = window.A2_VOCAB_21;
  window.BOOK0.forEach(chapter => {
    const list = fresh[chapter.num];
    if (!list) return;
    const previous = (chapter.vocab || []).map((card, index) => ({ card, index, key: key(card.w) }));
    const byKey = new Map();
    previous.forEach(entry => {
      if (!byKey.has(entry.key)) byKey.set(entry.key, []);
      byKey.get(entry.key).push(entry);
    });
    const claimed = new Set();
    const merged = list.map(card => {
      const old = (byKey.get(key(card.w)) || []).find(entry => !claimed.has(entry.index));
      const next = { ...card };
      if (old) {
        claimed.add(old.index);
        if (old.card.img) next.img = old.card.img;
        next.legacy = { index: old.index, w: old.card.w };
      }
      return next;
    });
    /* older words that are not in the new list stay at the end, with their saved ids */
    const ownKeys = new Set(list.map(card => key(card.w)));
    const extras = previous.filter(entry => !claimed.has(entry.index) && !ownKeys.has(entry.key)).map(entry => ({
      ...entry.card, cat: 'Weitere nützliche Wörter', catAr: 'كلمات وعبارات إضافية مفيدة', legacy: { index: entry.index, w: entry.card.w }
    }));
    chapter.vocab = [...merged, ...extras];
    chapter.vocabSummary = {
      title: 'Wortschatz zum Kapitel',
      titleAr: 'مفردات الوحدة',
      note: 'Alle Wörter aus dem Lernwortschatz und der Wortliste von Netzwerk neu A2.1, nach Themen sortiert – mit einfacher Erklärung und Beispielsatz.',
      noteAr: 'كل كلمات الـ Lernwortschatz وقائمة الكلمات للوحدة من Netzwerk neu A2.1، مرتبة حسب الموضوع، مع شرح بسيط بالألماني ومثال وترجمة.'
    };
  });
})();
