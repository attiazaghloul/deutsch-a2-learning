/* Inventory and exact-headword photo reuse. Run after slicing each new sheet. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../..'),app=path.join(root,'app');
const ctx={console};ctx.window=ctx;vm.createContext(ctx);
const html=fs.readFileSync(path.join(app,'index.html'),'utf8');
for(const match of html.matchAll(/<script src="(data_[^"?]+\.js)/g)){
 if(match[1]==='data_vocab_images.js')continue;
 vm.runInContext(fs.readFileSync(path.join(app,match[1]),'utf8'),ctx,{filename:match[1]});
}
const books={A1:ctx.A1_BOOK,A2:[...ctx.BOOK0,...ctx.BOOK1,...ctx.BOOK2],B1:ctx.B1_BOOK};
const limits={1:40,2:40,3:34,4:36,5:34,6:40,7:136,8:49,9:49,10:52,11:49,12:52};
// Preserve capitalization: formal Sie and informal sie must not share a scene.
const key=w=>w.split(',')[0].trim().normalize('NFC');
const exists=src=>fs.existsSync(path.join(app,src));
const known=new Map(),mapping={},cards=[],broken=[];
for(const [level,book] of Object.entries(books))for(const chapter of book)chapter.vocab.forEach((v,index)=>{
 const id=`${level}|${chapter.num}|${v.w}`;
 let src=v.img;
 if(!src&&level==='A2'){
  // Expanded A2.1 vocabulary retains the ORIGINAL image position in legacy.index.
  const oldIndex=v.legacy?.index??(chapter.num>6?index:-1);
  if(oldIndex>=0&&(oldIndex<limits[chapter.num]||(chapter.num===7&&[140,144,145].includes(oldIndex+1)))){
   src=`assets/vocab-scenes/k${chapter.num}/${String(oldIndex+1).padStart(2,'0')}.webp`;
  }
 }
 if(src&&!exists(src)){broken.push({id,src});src=null;}
 if(src){known.set(key(v.w),known.get(key(v.w))||src);if(!v.img)mapping[id]=src;}
 cards.push({id,level,chapter:chapter.num,word:v.w,definition:v.d,example:v.ex,ar:v.ar,src});
});
// Generated pictures take precedence over a reused picture, never over an original picture.
const deliveredPath=path.join(__dirname,'delivered.json');
const delivered=fs.existsSync(deliveredPath)?JSON.parse(fs.readFileSync(deliveredPath,'utf8')):{};
for(const [word,src] of Object.entries(delivered)){
 if(!exists(src))throw new Error(`Delivered image missing: ${src}`);
 known.set(word,src);
}
let reused=0;
for(const card of cards)if(!card.src&&known.has(key(card.word))){card.src=known.get(key(card.word));mapping[card.id]=card.src;reused++;}
const pending=new Map();
for(const card of cards)if(!card.src&&!pending.has(key(card.word)))pending.set(key(card.word),card);
const groups=[...pending.values()];
const report={cards:cards.length,covered:cards.filter(c=>c.src).length,missingCards:cards.filter(c=>!c.src).length,reused,broken,remainingUnique:groups.length,sheets:Math.ceil(groups.length/16),chapters:Object.entries(books).flatMap(([level,book])=>book.map(c=>{const rows=cards.filter(v=>v.level===level&&v.chapter===c.num);return {level,chapter:c.num,total:rows.length,covered:rows.filter(v=>v.src).length};}))};
fs.writeFileSync(path.join(__dirname,'audit.json'),JSON.stringify(report,null,2)+'\n');
fs.writeFileSync(path.join(__dirname,'pending.json'),JSON.stringify(Array.from({length:Math.ceil(groups.length/16)},(_,i)=>({sheet:i+1,cells:groups.slice(i*16,(i+1)*16)})),null,2)+'\n');
fs.writeFileSync(path.join(app,'data_vocab_images.js'),`/* Generated by scripts/vocab_images/build.cjs. Exact words only; no category placeholders. */\nwindow.VOCAB_IMAGES = ${JSON.stringify(mapping,null,1)};\n(function(){\n const books={A1:window.A1_BOOK,A2:[...window.BOOK0,...window.BOOK1,...window.BOOK2],B1:window.B1_BOOK};\n for(const [level,book] of Object.entries(books))for(const chapter of book)for(const card of chapter.vocab||[]){\n  const src=window.VOCAB_IMAGES[level+'|'+chapter.num+'|'+card.w];\n  if(src&&!card.img)card.img=src;\n }\n})();\n`);
console.log(JSON.stringify(report,null,2));
if(broken.length)process.exitCode=1;
