/* Build app/data_practice.js: the sentences for Shadowing and Diktat.

   Every chapter of A1, A2 and B1 gets the German sentences it already
   teaches: conversation phrases and dialogue lines (with their Arabic), set
   phrases from the Redemittel, and the vocabulary examples that have a
   recording. Sentences with a recording (Mia/Tarek) come first; the others
   play with the device voice.

   Run after changing chapter content or the speech libraries:
     node scripts/build_practice_sentences.js
   (test/app.test.js fails while the output is stale). */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const APP = path.join(ROOT, 'app');
const OUTPUT = 'app/data_practice.js';
const PER_CHAPTER = 48;
const SPEECH = ['data_speech_a1.js', 'data_speech_clean.js'];

function loadData() {
  const html = fs.readFileSync(path.join(APP, 'index.html'), 'utf8');
  const sources = [...html.matchAll(/<script src="(data_[^"?]+)/g)].map(match => match[1]);
  const context = {};
  context.window = context;
  vm.createContext(context);
  for (const file of [...sources, ...SPEECH]) {
    vm.runInContext(fs.readFileSync(path.join(APP, file), 'utf8'), context, { filename: file });
  }
  return context;
}

const clean = text => String(text || '').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

// A sentence to repeat: whole, German, 2 to 18 words, no gaps or alternatives.
function usable(text) {
  if (!/^[A-ZÄÖÜa-zäöüß„"]/.test(text) || !/[.!?]["“”]?$/.test(text)) return false;
  if (/…|\.\.\.|_{2,}|\/|\(|\)|\[|=|→|\+|[؀-ۿ]/.test(text)) return false;
  const words = text.split(' ').length;
  return words >= 2 && words <= 18;
}

function chapterSentences(chapter, recorded) {
  const found = new Map();
  const add = (de, ar, source) => {
    const text = clean(de);
    if (!usable(text) || found.has(text)) return;
    found.set(text, { de: text, ar: clean(ar), rec: recorded.has(text) ? 1 : 0, source });
  };
  for (const conversation of chapter.conversations || []) {
    for (const phrase of conversation.phrases || []) add(phrase.de, phrase.ar, 'phrase');
    for (const line of conversation.dialogue || []) add(line.de, line.ar, 'dialogue');
  }
  for (const group of chapter.redemittel || []) {
    for (const item of group.items || []) add(item.de, item.ar, 'redemittel');
  }
  for (const word of chapter.vocab || []) {
    if (word.ex && recorded.has(clean(word.ex))) add(word.ex, '', 'example');
  }
  // recorded sentences first, then the original order
  return [...found.values()]
    .map((item, index) => ({ item, index }))
    .sort((left, right) => right.item.rec - left.item.rec || left.index - right.index)
    .slice(0, PER_CHAPTER)
    .map(({ item }) => {
      const out = { de: item.de };
      if (item.ar) out.ar = item.ar;
      if (item.rec) out.rec = 1;
      return out;
    });
}

function build() {
  const data = loadData();
  const recorded = new Set([
    ...data.A1_FIXED_SPEECH.texts,
    ...data.A2_FIXED_SPEECH.texts,
    ...(data.A2_FIXED_SPEECH.aliases?.texts || [])
  ]);
  const levels = {
    a1: data.A1_BOOK,
    a2: [...data.BOOK0, ...data.BOOK1, ...data.BOOK2],
    b1: data.B1_BOOK
  };
  const practice = {};
  for (const [level, book] of Object.entries(levels)) {
    practice[level] = book.map(chapter => ({
      num: chapter.num,
      title: chapter.title,
      titleAr: chapter.titleAr || '',
      sentences: chapterSentences(chapter, recorded)
    }));
  }
  return `/* Generated by scripts/build_practice_sentences.js from the chapters and the speech libraries. Do not edit. */\nwindow.PRACTICE_SENTENCES=${JSON.stringify(practice)};\n`;
}

if (require.main === module) {
  const output = build();
  fs.writeFileSync(path.join(ROOT, OUTPUT), output);
  const practice = JSON.parse(output.slice(output.indexOf('=') + 1, -2));
  for (const [level, chapters] of Object.entries(practice)) {
    const sentences = chapters.flatMap(chapter => chapter.sentences);
    console.log(`${level}: ${sentences.length} sentences, ${sentences.filter(item => item.rec).length} recorded, ${sentences.filter(item => item.ar).length} with Arabic`);
  }
  console.log(`${OUTPUT}: ${(output.length / 1024).toFixed(1)} KB`);
}

module.exports = { build, OUTPUT, usable };
