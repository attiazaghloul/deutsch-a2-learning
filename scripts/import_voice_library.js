/* Turn the B1 recordings into app/data_speech_b1.js.

   .github/workflows/record-voices.yml records them on GitHub (Edge TTS) into
   app/assets/speech/b1/<voice>-<part>.mp3 and scripts/voices/b1-timings.json.
   After the recordings are checked:
     node scripts/import_voice_library.js
   The texts must still be the ones scripts/extract_b1_speech_library.js
   writes (build/b1-speech-library-texts.json), or the clips would not match. */
const fs = require('fs');
const path = require('path');

const AUDIO_BASE = 'assets/speech/';
const TIMINGS = path.join(__dirname, 'voices', 'b1-timings.json');
const OUTPUT = path.join(__dirname, '..', 'app', 'data_speech_b1.js');

function build(timingsPath, expectedTextsPath) {
  const data = JSON.parse(fs.readFileSync(timingsPath, 'utf8'));
  if (expectedTextsPath && fs.existsSync(expectedTextsPath)) {
    const expected = JSON.parse(fs.readFileSync(expectedTextsPath, 'utf8'));
    if (JSON.stringify(expected) !== JSON.stringify(data.texts)) {
      throw new Error('The recorded texts differ from the current B1 texts: copy build/b1-speech-library-texts.json to scripts/voices/b1-texts.json and record again.');
    }
  }
  for (const voice of data.voices) {
    if (voice.timings.length !== data.texts.length || voice.timings.some(timing => !Array.isArray(timing) || timing.length !== 3)) {
      throw new Error(`${voice.id}: incomplete timings`);
    }
  }
  const library = {
    version: data.version,
    trimmed: true,
    texts: data.texts,
    voices: data.voices.map(voice => ({
      id: voice.id,
      name: voice.name,
      description: voice.description,
      parts: voice.parts.map(part => `${AUDIO_BASE}${part}?v=${data.version}`),
      timings: voice.timings
    }))
  };
  return `/* Generated by scripts/import_voice_library.js from scripts/voices/b1-timings.json. Do not edit.\n   Voices: ${library.voices.map(voice => `${voice.name} (${voice.parts.length} files)`).join(', ')}. */\nwindow.B1_FIXED_SPEECH=${JSON.stringify(library)};\n`;
}

if (require.main === module) {
  const [timingsPath = TIMINGS, textsPath = path.join(__dirname, '..', 'build', 'b1-speech-library-texts.json')] = process.argv.slice(2);
  const output = build(timingsPath, textsPath);
  fs.writeFileSync(OUTPUT, output);
  console.log(`${path.relative(process.cwd(), OUTPUT)}: ${(output.length / 1024 / 1024).toFixed(1)} MB`);
}

module.exports = { build, AUDIO_BASE };
