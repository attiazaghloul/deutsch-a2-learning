/* Put the voices recorded by .github/workflows/record-voices.yml into the app.

   The workflow records into app/assets/speech/<level>/<voice>-<part>.mp3 and
   writes scripts/voices/<level>-<voice>-timings.json. After the recordings
   are checked (scripts/verify_voices.py):
     node scripts/import_voice_library.js
   writes
     - app/data_speech_b1.js from b1 (Mia, Tarek),
     - Mia in app/data_speech_a1.js from a1,
     - Mia in app/data_speech_clean.js from a2 (sentences) and a2words (words),
   keeping every other voice as it is. A recording whose texts differ from the
   library's texts is refused: its clips would not match. */
const fs = require('fs');
const path = require('path');

const AUDIO_BASE = 'assets/speech/';
const VOICES_DIR = path.join(__dirname, 'voices');
const APP = path.join(__dirname, '..', 'app');

function readRecording(file) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const voice = data.voice;
  if (voice.timings.length !== data.texts.length || voice.timings.some(timing => !Array.isArray(timing) || timing.length !== 3)) {
    throw new Error(`${path.basename(file)}: incomplete timings`);
  }
  return {
    texts: data.texts,
    voice: {
      id: voice.id,
      name: voice.name,
      description: voice.description,
      parts: voice.parts.map(part => `${AUDIO_BASE}${part}?v=${data.version}`),
      timings: voice.timings
    }
  };
}

function sameTexts(left, right, label) {
  if (JSON.stringify(left) !== JSON.stringify(right)) throw new Error(`${label}: the recorded texts differ from the library`);
}

// Replace one voice of a library ({texts, voices}) with a recording.
function withVoice(library, recording, label) {
  sameTexts(library.texts, recording.texts, label);
  const voices = library.voices.some(voice => voice.id === recording.voice.id)
    ? library.voices.map(voice => voice.id === recording.voice.id ? recording.voice : voice)
    : [...library.voices, recording.voice];
  return { ...library, voices };
}

function readLibrary(file, name) {
  const source = fs.readFileSync(file, 'utf8');
  const start = source.indexOf(`window.${name}=`);
  return { head: source.slice(0, start), data: JSON.parse(source.slice(start + name.length + 8).replace(/;\s*$/, '')) };
}

function writeLibrary(file, name, head, data) {
  fs.writeFileSync(file, `${head}window.${name}=${JSON.stringify(data)};\n`);
}

function buildB1(recordings, expectedTexts) {
  if (expectedTexts) sameTexts(expectedTexts, recordings[0].texts, 'b1');
  recordings.forEach(recording => sameTexts(recordings[0].texts, recording.texts, 'b1'));
  const library = { version: 'b1-voices-1', trimmed: true, texts: recordings[0].texts, voices: recordings.map(recording => recording.voice) };
  return `/* Generated by scripts/import_voice_library.js from scripts/voices/b1-*-timings.json. Do not edit.\n   Voices: ${library.voices.map(voice => `${voice.name} (${voice.parts.length} files)`).join(', ')}. */\nwindow.B1_FIXED_SPEECH=${JSON.stringify(library)};\n`;
}

function recording(level, voice) {
  const file = path.join(VOICES_DIR, `${level}-${voice}-timings.json`);
  return fs.existsSync(file) ? readRecording(file) : null;
}

if (require.main === module) {
  const done = [];
  const b1 = ['mia', 'tarek'].map(voice => recording('b1', voice)).filter(Boolean);
  if (b1.length) {
    const textsFile = path.join(VOICES_DIR, 'b1-texts.json');
    fs.writeFileSync(path.join(APP, 'data_speech_b1.js'), buildB1(b1, JSON.parse(fs.readFileSync(textsFile, 'utf8'))));
    done.push(`B1: ${b1.map(item => item.voice.id).join(', ')}`);
  }
  const a1 = recording('a1', 'mia');
  if (a1) {
    const file = path.join(APP, 'data_speech_a1.js');
    const { head, data } = readLibrary(file, 'A1_FIXED_SPEECH');
    writeLibrary(file, 'A1_FIXED_SPEECH', head, { ...withVoice(data, a1, 'a1'), trimmed: true });
    done.push('A1: mia');
  }
  const a2 = recording('a2', 'mia');
  const words = recording('a2words', 'mia');
  if (a2 || words) {
    const file = path.join(APP, 'data_speech_clean.js');
    let { head, data } = readLibrary(file, 'A2_FIXED_SPEECH');
    if (a2) data = withVoice(data, a2, 'a2');
    if (words) data = { ...data, aliases: withVoice(data.aliases, words, 'a2words') };
    writeLibrary(file, 'A2_FIXED_SPEECH', head, data);
    done.push(`A2: ${[a2 && 'mia', words && 'mia words'].filter(Boolean).join(', ')}`);
  }
  console.log(done.length ? `imported ${done.join('; ')}` : 'no recordings found in scripts/voices/');
}

module.exports = { readRecording, withVoice, buildB1, AUDIO_BASE };
