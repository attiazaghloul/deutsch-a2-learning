/* Turn the B1 recordings of the deutsch-audio repository into app/data_speech_b1.js.

   The B1 voices are too large for this site (GitHub Pages allows 1 GB), so
   they are recorded and served by https://github.com/attiazaghloul/deutsch-audio
   (GitHub Actions records them with Edge TTS, GitHub Pages serves them on the
   same github.io origin). This reads its b1/timings.json:
     node scripts/import_voice_library.js ../deutsch-audio/b1/timings.json
   The texts must be the ones scripts/extract_b1_speech_library.js writes
   today (build/b1-speech-library-texts.json), or the clips would not match. */
const fs = require('fs');
const path = require('path');

const AUDIO_SITE = 'https://attiazaghloul.github.io/deutsch-audio/';
const OUTPUT = path.join(__dirname, '..', 'app', 'data_speech_b1.js');

function build(timingsPath, expectedTextsPath) {
  const data = JSON.parse(fs.readFileSync(timingsPath, 'utf8'));
  if (expectedTextsPath && fs.existsSync(expectedTextsPath)) {
    const expected = JSON.parse(fs.readFileSync(expectedTextsPath, 'utf8'));
    if (JSON.stringify(expected) !== JSON.stringify(data.texts)) {
      throw new Error('The recorded texts differ from the current B1 texts: copy build/b1-speech-library-texts.json to deutsch-audio/texts/b1.json and record again.');
    }
  }
  for (const voice of data.voices) {
    if (voice.timings.length !== data.texts.length || voice.timings.some(timing => !Array.isArray(timing) || timing.length !== 3)) {
      throw new Error(`${voice.id}: incomplete timings`);
    }
  }
  const library = {
    version: data.version,
    trimmed: true,
    texts: data.texts,
    voices: data.voices.map(voice => ({
      id: voice.id,
      name: voice.name,
      description: voice.description,
      parts: voice.parts.map(part => `${AUDIO_SITE}${part}?v=${data.version}`),
      timings: voice.timings
    }))
  };
  return `/* Generated by scripts/import_voice_library.js from the deutsch-audio recordings. Do not edit.\n   Voices: ${library.voices.map(voice => `${voice.name} (${voice.parts.length} files)`).join(', ')}. */\nwindow.B1_FIXED_SPEECH=${JSON.stringify(library)};\n`;
}

if (require.main === module) {
  const [timingsPath, textsPath = path.join(__dirname, '..', 'build', 'b1-speech-library-texts.json')] = process.argv.slice(2);
  if (!timingsPath) throw new Error('usage: node scripts/import_voice_library.js <deutsch-audio>/b1/timings.json');
  const output = build(timingsPath, textsPath);
  fs.writeFileSync(OUTPUT, output);
  console.log(`${path.relative(process.cwd(), OUTPUT)}: ${(output.length / 1024 / 1024).toFixed(1)} MB`);
}

module.exports = { build, AUDIO_SITE };
